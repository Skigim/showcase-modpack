"""One window for the boss-footage setup: hero and boss attacks.

    python wiki_setup.py            the window
    python wiki_setup.py --write    write every file from settings.json, no window, no apply

Everything here is a data patch: Save writes the mods and runs `rsmm apply`,
which needs the game closed, and it shows on the next launch. So while
Ravenswatch.exe runs, the controls are locked. Each section's "Reset to normal"
(then Save) leaves its mod enabled but empty. The camera is not this pack's:
use Ovilli's camera-control mod, which changes it live.

Files it owns (each is overwritten on Save):
    mods/WikiScene/manifest.toml          hero toggles
    tools/boss_attacks/selection.json, attacks.txt, mods/BossAttackRoll/manifest.toml
                                          via boss_attacks.py, so its command and
                                          attacks.txt keep working
"""

from __future__ import annotations

import json
import os
import queue
import subprocess
import sys
import threading
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parent / "boss_attacks"))
import boss_attacks as ba  # noqa: E402
import paths  # noqa: E402

SETTINGS = HERE / "settings.json"
SCENE_MANIFEST = paths.MODS / "WikiScene" / "manifest.toml"
PROCESS_NAME = "Ravenswatch.exe"
NO_WINDOW = getattr(subprocess, "CREATE_NO_WINDOW", 0)

HERO = [                    # key, label
    ("hide_hero", "Hide the hero (body and weapon)"),
    ("invincible", "Hero can't be hurt"),
    ("hide_marks", "Hide the ground shadow and aim arrow"),
    ("hide_lifebar", "Hide the bar above the hero (health, energy, pips)"),
]
DEFAULTS = {k: False for k, _ in HERO}   # what the pack ships


# ---------------------------------------------------------------- files

def _scene(saved: dict) -> dict:
    """DEFAULTS filled in from a saved scene; keys no longer used (the old distance) drop out."""
    return {k: saved.get(k, v) for k, v in DEFAULTS.items()}


def load_settings() -> dict:
    s = {"scene": dict(DEFAULTS), "applied": None}
    if SETTINGS.is_file():
        s.update(json.loads(SETTINGS.read_text(encoding="utf-8")))
        s["scene"] = _scene(s["scene"])
    if s["applied"] is None:    # first run: the pack as shipped
        s["applied"] = {"scene": dict(DEFAULTS), "attacks": ba.load_selection()}
    else:
        s["applied"]["scene"] = _scene(s["applied"]["scene"])
    return s


def save_settings(s: dict) -> None:
    SETTINGS.write_text(json.dumps(s, indent=2) + "\n", encoding="utf-8")


SCENE_HEADER = """\
#:schema https://docs.rsmm.me/manifest.schema.json
# GENERATED by tools/wiki_setup/wiki_setup.py -- change it in that window,
# not by hand: the next Save overwrites this file.
# Every edit is on Hero_Common, the parent of every hero. Proven in game
# 2026-10-15 (Chapter 1). None touches the hero's Is Targetable Condition,
# so bosses still attack. Stay out of cinematics: they make the hero Concealed.
[mod]
id                = "WikiScene"
name              = "Wiki Scene"
version           = "1.0.0"
author            = "Skigim"
summary           = "Hides the hero and keeps it alive, for filming bosses."
description       = "Boss footage aid: the hero, its ground shadow, aim arrow and lifebar are hidden, and it can't be hurt while bosses still target it. Each part is toggled in the wiki_setup window. With everything off it changes nothing. Affects every hero while on."
license           = "MIT"
repo_url          = "https://github.com/Skigim/showcase-modpack"
tags              = ["hero", "showcase", "wiki"]
enabled           = {enabled}
multiplayer_scope = "deterministic-shared"
sdk_version       = ">=3.0,<4"
"""


def _set(path: str, value: str) -> str:
    return f"\n[[content.steps]]\nset   = '{path}'\nvalue = {value}\n"


def _add_link(path: str, to: str) -> str:
    return f"\n[[content.steps]]\nadd_link = '{path}'\nto       = '{to}'\n"


def _remove_link(path: str) -> str:
    return f"\n[[content.steps]]\nremove_link = '{path}'\n"


def scene_manifest(scene: dict) -> str:
    steps = []
    if scene["hide_hero"]:
        steps.append("\n# HIDE: the Appear Value Selector's literal fallback 1.0 -> 0 (u_appear dissolve).")
        steps.append(_set(r"Shading\Appear Value Selector.entries[10][1]", "0"))
    if scene["invincible"]:
        steps.append("\n# INVINCIBLE: the debug cheat state held from normal behaviour; targeting untouched.")
        steps.append(_add_link("Behaviour Default.while_active", "_DBG State Invincible Cheat"))
        steps.append(_add_link("Behaviour Interacting.while_active", "_DBG State Invincible Cheat"))
    if scene["hide_marks"]:
        steps.append("\n# SHADOW and AIM ARROW decals: visible flag off (polarity inferred) and scale ~0.")
        for decal in (r"Base\Ground Shadow", r"Base\Ground Marker"):
            steps.append(_set(decal + ".value_5", "false"))
            steps.append(_set(decal + ".value_10", "0.0001"))
    if scene["hide_lifebar"]:
        steps.append("\n# LIFEBAR (with energy/resource pips) never spawned. Display only.")
        steps.append(_remove_link(r"Life Bar\State Player Lifebar.while_active[0]"))
        steps.append(_remove_link(r"Life Bar\State Peer Lifebar.while_active[0]"))
    # Everything at normal = no [[content]]: the mod stays enabled and changes nothing.
    out = [SCENE_HEADER.format(enabled="true")]
    if steps:
        out.append('\n[[content]]\nkind   = "entity"\nid     = "wiki_scene"\n'
                   'entity = "Heroes/Hero_Common/Hero_Common"\n')
        out += steps
    return "".join(out)


def write_data(scene: dict, attacks: dict) -> None:
    """Every data-patch file. Nothing reaches the game until `rsmm apply`."""
    tables = ba.load_tables()
    ba.SELECTION.write_text(json.dumps(attacks, indent=2) + "\n", encoding="utf-8")
    ba.write_attacks_file(tables, attacks)
    ba.MOD_DIR.mkdir(parents=True, exist_ok=True)
    (ba.MOD_DIR / "manifest.toml").write_text(ba.manifest(tables, attacks), encoding="utf-8")
    SCENE_MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    SCENE_MANIFEST.write_text(scene_manifest(scene), encoding="utf-8")


def game_running() -> bool:
    try:
        p = subprocess.run(["tasklist", "/FI", f"IMAGENAME eq {PROCESS_NAME}", "/NH"],
                           capture_output=True, text=True, timeout=5, creationflags=NO_WINDOW)
    except (OSError, subprocess.SubprocessError):
        return False
    return PROCESS_NAME.lower() in (p.stdout or "").lower()


# ---------------------------------------------------------------- window

def run_window() -> None:
    import tkinter as tk
    from tkinter import ttk
    from tkinter.scrolledtext import ScrolledText

    settings = load_settings()
    tables = ba.load_tables()
    bosses = sorted(tables.values(), key=lambda t: t["label"])   # chapter order
    selection = ba.load_selection()

    root = tk.Tk()
    root.title("Wiki boss setup")
    root.minsize(560, 0)
    pad = {"padx": 10, "pady": 4}

    banner = tk.Label(root, anchor="w", justify="left", font=("Segoe UI", 10, "bold"), padx=10, pady=6)
    banner.pack(fill="x")

    # hero
    locked = []   # widgets that only change with the game closed
    hero = ttk.LabelFrame(root, text="Hero  (next launch)")
    hero.pack(fill="x", **pad)
    hero_vars = {}
    for i, (key, label) in enumerate(HERO):
        v = tk.BooleanVar(value=bool(settings["scene"][key]))
        hero_vars[key] = v
        cb = ttk.Checkbutton(hero, text=label, variable=v)
        cb.grid(row=i, column=0, sticky="w", padx=8, pady=1)
        locked.append(cb)

    def reset_hero():
        for v in hero_vars.values():
            v.set(False)
    b = ttk.Button(hero, text="Reset to normal", command=reset_hero)
    b.grid(row=0, column=1, sticky="ne", padx=8, pady=(4, 0))
    hero.columnconfigure(1, weight=1)
    locked.append(b)

    # attacks
    atk = ttk.LabelFrame(root, text="Boss attacks  (next launch; all ticked = normal)")
    atk.pack(fill="x", **pad)
    atk_vars = {}
    row = 0
    for t in bosses:
        chosen = selection.get(t["id"])
        ttk.Label(atk, text=t["label"]).grid(row=row, column=0, columnspan=4, sticky="w", padx=8, pady=(6, 0))
        row += 1
        atk_vars[t["id"]] = {}
        for j, a in enumerate(t["attacks"]):
            v = tk.BooleanVar(value=(not chosen) or a["name"] in chosen)
            atk_vars[t["id"]][a["name"]] = v
            cb = ttk.Checkbutton(atk, text=a["name"], variable=v)
            cb.grid(row=row + j // 4, column=j % 4, sticky="w", padx=(20 if j % 4 == 0 else 8, 8))
            locked.append(cb)
        row += (len(t["attacks"]) + 3) // 4
        if "proven" not in t.get("status", ""):
            ttk.Label(atk, foreground="gray", text="untested in game").grid(row=row, column=0, columnspan=4, sticky="w", padx=20)
            row += 1
    ttk.Label(atk, foreground="gray", text="One attack per boss is proven; several at once is untested.").grid(
        row=row, column=0, columnspan=4, sticky="w", padx=8, pady=(6, 6))

    def reset_attacks():
        for d in atk_vars.values():
            for v in d.values():
                v.set(True)
    b = ttk.Button(atk, text="Reset to normal", command=reset_attacks)
    b.grid(row=0, column=4, sticky="ne", padx=8, pady=(4, 0))
    atk.columnconfigure(4, weight=1)
    locked.append(b)

    # save + log
    bar = ttk.Frame(root)
    bar.pack(fill="x", **pad)
    save_btn = ttk.Button(bar, text="Save")
    save_btn.pack(side="left")
    pending = ttk.Label(bar, foreground="#b35c00")
    pending.pack(side="left", padx=10)
    log = ScrolledText(root, height=10, font=("Consolas", 9), state="disabled")
    log.pack(fill="both", expand=True, padx=10, pady=(0, 10))

    def say(text: str) -> None:
        log.config(state="normal")
        log.insert("end", text.rstrip("\n") + "\n")
        log.see("end")
        log.config(state="disabled")

    def current() -> tuple[dict, dict | str]:
        scene = {k: v.get() for k, v in hero_vars.items()}
        attacks = {}
        for t in bosses:
            names = [n for n, v in atk_vars[t["id"]].items() if v.get()]
            if not names:
                return scene, f"{t['label']}: tick at least one attack (all ticked = normal)."
            if len(names) < len(t["attacks"]):
                attacks[t["id"]] = names
        return scene, attacks

    state = {"running": None, "busy": False}
    out_q: queue.Queue = queue.Queue()

    def refresh(check_game: bool = False) -> None:
        running = game_running() if check_game else state["running"]   # tasklist only on the 2 s poll
        if running != state["running"]:
            state["running"] = running
            if running:
                banner.config(text="Game is running: close it to change the hero or the attacks.",
                              bg="#fde7c8")
            else:
                banner.config(text="Game is closed: Save installs everything for the next launch.", bg="#d8efd8")
            for w in locked:
                w.state(["disabled"] if running else ["!disabled"])
        scene, attacks = current()
        applied = settings["applied"]
        if not isinstance(attacks, str) and (scene != applied["scene"] or attacks != applied["attacks"]):
            pending.config(text="hero/attack changes not installed yet")
        else:
            pending.config(text="")
        save_btn.state(["disabled"] if state["busy"] else ["!disabled"])

    def poll_game() -> None:
        refresh(check_game=True)
        root.after(2000, poll_game)

    def drain() -> None:
        try:
            while True:
                kind, payload = out_q.get_nowait()
                if kind == "line":
                    say(payload)
                else:   # done
                    rc, scene, attacks = payload
                    state["busy"] = False
                    if rc == 0:
                        settings["applied"] = {"scene": scene, "attacks": attacks}
                        save_settings(settings)
                        say("Installed. It shows on the next game launch.")
                    else:
                        say(f"rsmm apply failed (exit {rc}); the game keeps what it had. See above.")
                    refresh()
        except queue.Empty:
            pass
        root.after(100, drain)

    def apply_thread(scene: dict, attacks: dict) -> None:
        env = {**os.environ, "NO_COLOR": "1", "PYTHONIOENCODING": "utf-8"}
        try:
            p = subprocess.Popen(paths.apply_command(), cwd=str(paths.rsmm_dir()),
                                 stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                 text=True, encoding="utf-8", errors="replace", env=env,
                                 creationflags=NO_WINDOW)
            for line in p.stdout:
                out_q.put(("line", line))
            rc = p.wait()
        except OSError as e:    # FileNotFoundError from paths names the fix
            out_q.put(("line", f"could not run rsmm apply: {e}"))
            rc = -1
        out_q.put(("done", (rc, scene, attacks)))

    def save() -> None:
        scene, attacks = current()
        if isinstance(attacks, str):
            say(attacks)
            return
        if game_running():
            say("Game is running, so nothing was saved. Close it and Save again.")
            refresh()
            return
        settings["scene"] = scene
        save_settings(settings)
        write_data(scene, attacks)
        say("Mods written; running rsmm apply...")
        state["busy"] = True
        refresh()
        threading.Thread(target=apply_thread, args=(scene, attacks), daemon=True).start()

    save_btn.config(command=save)
    for v in [*hero_vars.values(),*(v for d in atk_vars.values() for v in d.values())]:
        v.trace_add("write", lambda *_: refresh())
    poll_game()
    drain()
    root.mainloop()


def main(argv: list[str]) -> int:
    if "--write" in argv:
        s = load_settings()
        write_data(s["scene"], ba.load_selection())
        print("written; not applied")
        return 0
    run_window()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

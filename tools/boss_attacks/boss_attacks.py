"""Choose which attacks each chapter boss uses, then apply it to the game.

    boss-attacks                          list bosses, attacks and the current choice
    boss-attacks <boss> <attack> [...]    only these attacks for that boss, then apply
    boss-attacks <boss> all               that boss back to vanilla, then apply
    boss-attacks off                      every boss back to vanilla, then apply
                                          (the mod stays enabled, with nothing in it)
    boss-attacks file                     take the choice from attacks.txt, then apply
    add --no-apply to any of them to only write the manifest

attacks.txt is the no-command way: edit it, save, double-click
"Apply boss attacks.cmd". Every command above rewrites it to match.

Attack names are the wiki/clip names or the game-data names, any case
(e.g. FastSlam, fast_slam, "Spread Projectiles"). Bosses come from
tables/<boss>.json. The choice is a static data patch: close the game first,
and it takes effect on the next launch.

Writes mods/BossAttackRoll/manifest.toml in this pack. Each listed attack gets
weight 1000, every other attack 0, and the boss draws exactly that many attacks
into its pool. The boss first has to take its newer pattern path, which the
pre_steps in each table force.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import paths  # noqa: E402

TABLES = HERE / "tables"
SELECTION = HERE / "selection.json"
ATTACKS_FILE = HERE / "attacks.txt"
MOD_DIR = paths.MODS / "BossAttackRoll"
WEIGHT_ON = 1000

HEADER = """\
#:schema https://docs.rsmm.me/manifest.schema.json
# GENERATED by tools/boss_attacks/boss_attacks.py (or the wiki_setup window) --
# change it there, not by hand: the next run overwrites this file.
[mod]
id                = "BossAttackRoll"
name              = "Boss Attack Roll"
version           = "1.0.0"
author            = "Skigim"
summary           = "Chapter bosses use only the attacks you pick."
description       = "Limits each chapter boss to the attacks chosen in tools/boss_attacks (attacks.txt) or the wiki_setup window, so one attack can be filmed on repeat. With nothing chosen it changes nothing."
license           = "MIT"
repo_url          = "https://github.com/Skigim/showcase-modpack"
tags              = ["boss", "showcase", "wiki"]
enabled           = true
multiplayer_scope = "deterministic-shared"
sdk_version       = ">=3.0,<4"
"""


def norm(s: str) -> str:
    return "".join(c for c in s.lower() if c.isalnum())


def load_tables() -> dict[str, dict]:
    tables = {}
    for p in sorted(TABLES.glob("*.json")):
        t = json.loads(p.read_text(encoding="utf-8"))
        tables[t["id"]] = t
    return tables


def load_selection() -> dict[str, list[str]]:
    if SELECTION.is_file():
        return json.loads(SELECTION.read_text(encoding="utf-8"))
    return {}


def find_attack(table: dict, name: str) -> dict | None:
    want = norm(name)
    for a in table["attacks"]:
        if want in (norm(a["name"]), norm(a["data"])):
            return a
    return None


def choose(table: dict, names: list[str]) -> list[str] | str:
    """Attack names -> the table's names in the order given; an error string if one is unknown."""
    chosen = []
    for name in names:
        a = find_attack(table, name)
        if not a:
            known = ", ".join(x["name"] for x in table["attacks"])
            return f"unknown attack {name!r} for {table['id']}; known: {known}"
        if a["name"] not in chosen:
            chosen.append(a["name"])
    return chosen


ATTACKS_HEADER = """\
# Boss attacks. After each boss's "=", write the attacks it may use,
# separated by commas. "all" (or nothing) = the vanilla attack set.
# Save, close the game, then double-click "Apply boss attacks.cmd".
# A line starting with # is ignored.
"""


def write_attacks_file(tables: dict, selection: dict) -> None:
    out = [ATTACKS_HEADER]
    for t in sorted(tables.values(), key=lambda t: t["label"]):   # chapter order
        chosen = selection.get(t["id"])
        out.append(f"\n# {t['label']}\n")
        out.append(f"#   attacks: {', '.join(a['name'] for a in t['attacks'])}\n")
        out.append(f"{t['id']} = {', '.join(chosen) if chosen else 'all'}\n")
    ATTACKS_FILE.write_text("".join(out), encoding="utf-8")


def read_attacks_file(tables: dict) -> dict | str:
    """attacks.txt -> a selection; an error string naming the bad line."""
    selection = {}
    lines = ATTACKS_FILE.read_text(encoding="utf-8-sig").splitlines()
    for n, raw in enumerate(lines, 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        boss, sep, rest = line.partition("=")
        boss = boss.strip().lower()
        if not sep or boss not in tables:
            return f"attacks.txt line {n}: expected '<boss> = <attacks>' with boss one of {', '.join(tables)}: {raw!r}"
        names = []
        for chunk in rest.split(","):
            chunk = chunk.strip()
            if not chunk:
                continue
            # "Spread Projectiles" is one name; "FastSlam Rain" (no comma) is two.
            names += [chunk] if find_attack(tables[boss], chunk) else chunk.split()
        if not names or (len(names) == 1 and names[0].lower() == "all"):
            selection.pop(boss, None)
            continue
        chosen = choose(tables[boss], names)
        if isinstance(chosen, str):
            return f"attacks.txt line {n}: {chosen}"
        if len(chosen) == len(tables[boss]["attacks"]):
            selection.pop(boss, None)           # every attack = vanilla
        else:
            selection[boss] = chosen
    return selection


def lit(s: str) -> str:
    # TOML literal string: backslashes stay as-is. Table paths never hold a quote.
    if "'" in s:
        raise ValueError(f"path contains a quote: {s!r}")
    return f"'{s}'"


def manifest(tables: dict, selection: dict) -> str:
    out = [HEADER]      # no bosses chosen = no [[content]]: enabled, but every boss vanilla
    for boss_id, chosen in selection.items():
        t = tables[boss_id]
        out.append(f"\n# {t['label']}: {', '.join(chosen)}\n# status: {t.get('status', '?')}\n")
        out.append(f'[[content]]\nkind   = "entity"\nid     = "pool_{boss_id}"\n'
                   f'entity = "{t["entity"]}"\n')
        for step in t.get("pre_steps", []):
            if "link" in step:
                out.append(f"\n[[content.steps]]\nlink = {lit(step['link'])}\nto   = {lit(step['to'])}\n")
            else:
                out.append(f"\n[[content.steps]]\nset   = {lit(step['set'])}\nvalue = {step['value']}\n")
        out.append(f"\n[[content.steps]]\nset   = {lit(t['draw_count'])}\nvalue = {len(chosen)}\n")
        for a in t["attacks"]:
            w = WEIGHT_ON if a["name"] in chosen else 0
            out.append(f"\n[[content.steps]]\nset   = {lit(a['weight'])}   # {a['name']}\nvalue = {w}\n")
    return "".join(out)


def show(tables: dict, selection: dict) -> None:
    for t in tables.values():
        chosen = selection.get(t["id"])
        print(f"{t['id']:<10} {t['label']}")
        print(f"           now: {', '.join(chosen) if chosen else 'vanilla (all attacks)'}")
        names = [a["name"] if a["name"] == a["data"] else f"{a['name']} ({a['data']})"
                 for a in t["attacks"]]
        print(f"           attacks: {', '.join(names)}")
        print(f"           status: {t.get('status', '?')}")
    print("\nusage: boss-attacks <boss> <attack> [...] | <boss> all | off   [--no-apply]")


def apply_mod() -> int:
    try:
        cmd = paths.apply_command()
    except FileNotFoundError as e:
        print(f"\n{e}")
        return 2
    print("\nApplying (the game must be closed)...")
    return subprocess.call(cmd, cwd=str(paths.rsmm_dir()))


def main(argv: list[str]) -> int:
    no_apply = "--no-apply" in argv
    args = [a for a in argv if a != "--no-apply"]
    tables = load_tables()
    selection = load_selection()
    if not args or args[0] in ("list", "-h", "--help"):
        show(tables, selection)
        return 0
    if args[0] == "off":
        selection = {}
    elif args[0] == "file":
        if not ATTACKS_FILE.is_file():
            write_attacks_file(tables, selection)
            print(f"wrote {ATTACKS_FILE.name} from the current choice; edit it, save, and run this again.")
            return 0
        selection = read_attacks_file(tables)
        if isinstance(selection, str):
            print(selection)
            return 2
    else:
        boss = args[0].lower()
        if boss not in tables:
            print(f"unknown boss {args[0]!r}; known: {', '.join(tables)}")
            return 2
        if len(args) < 2:
            print(f"name at least one attack for {boss}, or 'all'")
            return 2
        if len(args) == 2 and args[1].lower() == "all":
            selection.pop(boss, None)
        else:
            chosen = choose(tables[boss], args[1:])
            if isinstance(chosen, str):
                print(chosen)
                return 2
            if len(chosen) == len(tables[boss]["attacks"]):
                selection.pop(boss, None)       # every attack = vanilla
            else:
                selection[boss] = chosen
    SELECTION.write_text(json.dumps(selection, indent=2) + "\n", encoding="utf-8")
    write_attacks_file(tables, selection)
    MOD_DIR.mkdir(parents=True, exist_ok=True)
    (MOD_DIR / "manifest.toml").write_text(manifest(tables, selection), encoding="utf-8")
    show(tables, selection)
    if any(len(v) > 1 for v in selection.values()):
        print("\nnote: pools of more than one attack are untested in game (one attack is proven).")
    if no_apply:
        print("\nmanifest written; not applied (--no-apply).")
        return 0
    return apply_mod()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
